import assert from 'node:assert/strict';
import {build} from 'esbuild';
await build({entryPoints:['app/weather-model.ts'],outfile:'work/tests/weather-model.js',bundle:true,format:'esm',platform:'node'});
const {weatherKind,weatherSchema,cachedWeather,israelTime,ROME_WEATHER_URL,WEATHER_CACHE,WEATHER_MAX_AGE}=await import('../work/tests/weather-model.js');
for(const [code,kind] of [[0,'clear'],[1,'clear'],[2,'cloudy'],[3,'overcast'],[45,'fog'],[48,'fog'],[51,'rain'],[61,'rain'],[80,'rain'],[71,'snow'],[85,'snow'],[95,'storm'],[99,'storm'],[undefined,'neutral'],[4,'neutral']])assert.equal(weatherKind(code),kind);
assert.equal(israelTime(new Date('2026-11-14T22:05:00Z')),'00:05');
assert.equal(israelTime(new Date('2026-07-10T21:05:00Z')),'00:05');
const now=Date.parse('2026-11-14T22:15:00Z');
const current={time:now/1000-900,temperature_2m:12.8,is_day:0,weather_code:3,wind_speed_10m:2.1};
const storage={getItem:key=>{assert.equal(key,WEATHER_CACHE);return JSON.stringify({current,fetchedAt:now-1000});}};
assert.deepEqual(cachedWeather(storage,now),{current,fetchedAt:now-1000});
assert.equal(cachedWeather(storage,now+WEATHER_MAX_AGE),null);
assert.equal(cachedWeather({getItem:()=>'{bad'},now),null);
assert.equal(cachedWeather({getItem:()=>{throw Error('blocked')}},now),null);
assert(!weatherSchema.safeParse({...current,is_day:3}).success);
assert(!weatherSchema.safeParse({...current,temperature_2m:null}).success);
const url=new URL(ROME_WEATHER_URL);
assert.equal(url.hostname,'api.open-meteo.com');assert.equal(url.searchParams.get('latitude'),'41.9028');assert.equal(url.searchParams.get('longitude'),'12.4964');assert.equal(url.searchParams.get('timezone'),'Europe/Rome');
console.log('Passed: weather scenes, fixed Rome coordinates, Israel winter/summer time and safe stale/corrupt cache handling.');
